"""File and repository parsing routines."""

from __future__ import annotations

import ast
import hashlib
import time
from pathlib import Path

from app.models.schemas import ParsedFile, ParseSummary, ScanResult
from app.parser.ast_extractor import AstExtractor


def compute_module_name(rel_path: str) -> str:
    """Derive dotted Python module name from a relative file path.

    Examples:
        'auth/login.py' -> 'auth.login'
        'auth/__init__.py' -> 'auth'
        'pkg/subpkg/__init__.py' -> 'pkg.subpkg'
        'main.py' -> 'main'
        '__init__.py' -> '__init__'
    """
    posix_path = Path(rel_path).as_posix()
    if posix_path.endswith(".py"):
        posix_path = posix_path[:-3]
    parts = [part for part in posix_path.split("/") if part]
    if parts and parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts) if parts else "__init__"


def parse_file(abs_path: Path | str, rel_path: str) -> ParsedFile:
    """Parse a single Python file into a structured ParsedFile model.

    Reads the file with UTF-8 decoding and fallback replace handling.
    Catches syntax errors and I/O exceptions gracefully, returning a
    ParsedFile with `parse_error` populated instead of raising.

    Args:
        abs_path: Absolute filesystem path to the Python file.
        rel_path: Repository-relative POSIX file path.

    Returns:
        ParsedFile instance containing extracted AST entities or error details.
    """
    abs_p = Path(abs_path).resolve()
    rel_posix = Path(rel_path).as_posix()
    module_name = compute_module_name(rel_posix)

    try:
        raw_bytes = abs_p.read_bytes()
    except OSError as err:
        return ParsedFile(
            file_path=rel_posix,
            module_name=module_name,
            imports=[],
            classes=[],
            functions=[],
            module_docstring=None,
            line_count=0,
            content_hash="",
            parse_error=f"I/O error reading file: {err}",
        )

    content_hash = hashlib.sha256(raw_bytes).hexdigest()

    try:
        source_text = raw_bytes.decode("utf-8")
    except UnicodeDecodeError:
        source_text = raw_bytes.decode("utf-8", errors="replace")

    # Normalize universal newlines for consistent line slicing across OS platforms
    source_text = source_text.replace("\r\n", "\n").replace("\r", "\n")

    lines = source_text.splitlines(keepends=True)
    line_count = len(lines)

    try:
        tree = ast.parse(source_text, filename=rel_posix)
    except Exception as err:
        return ParsedFile(
            file_path=rel_posix,
            module_name=module_name,
            imports=[],
            classes=[],
            functions=[],
            module_docstring=None,
            line_count=line_count,
            content_hash=content_hash,
            parse_error=f"{type(err).__name__}: {err}",
        )

    extractor = AstExtractor(
        source_text=source_text,
        lines=lines,
        file_path=rel_posix,
        module_name=module_name,
    )
    extractor.extract(tree)

    return ParsedFile(
        file_path=rel_posix,
        module_name=module_name,
        imports=extractor.imports,
        classes=extractor.classes,
        functions=extractor.functions,
        module_docstring=extractor.module_docstring,
        line_count=line_count,
        content_hash=content_hash,
        parse_error=None,
    )


def parse_repository(scan_result: ScanResult) -> tuple[list[ParsedFile], ParseSummary]:
    """Parse all files in a repository scan result and produce a ParseSummary.

    Args:
        scan_result: ScanResult object generated by the repository scanner.

    Returns:
        Tuple of (list of ParsedFile, ParseSummary).
    """
    start_time = time.perf_counter()
    parsed_files: list[ParsedFile] = []
    errors: list[dict[str, str]] = []

    total_files = len(scan_result.files)
    parsed_ok = 0
    failed = 0
    total_functions = 0
    total_classes = 0
    total_methods = 0
    total_imports = 0
    total_calls = 0

    for file_info in scan_result.files:
        parsed = parse_file(abs_path=file_info.absolute_path, rel_path=file_info.path)
        parsed_files.append(parsed)

        if parsed.parse_error:
            failed += 1
            errors.append({"file": parsed.file_path, "error": parsed.parse_error})
        else:
            parsed_ok += 1
            total_imports += len(parsed.imports)
            total_classes += len(parsed.classes)
            total_functions += len(parsed.functions)
            for cls in parsed.classes:
                total_methods += len(cls.methods)
                for method in cls.methods:
                    total_calls += len(method.calls)
            for fn in parsed.functions:
                total_calls += len(fn.calls)

    duration = time.perf_counter() - start_time

    summary = ParseSummary(
        total_files=total_files,
        parsed_ok=parsed_ok,
        failed=failed,
        total_functions=total_functions,
        total_classes=total_classes,
        total_methods=total_methods,
        total_imports=total_imports,
        total_calls=total_calls,
        parse_time_seconds=round(duration, 4),
        errors=errors,
    )

    return parsed_files, summary
